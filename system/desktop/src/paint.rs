//! undo/redo, and save or open .bmp pictures.

use alloc::format;
use alloc::string::{String, ToString};
use alloc::vec;
use alloc::vec::Vec;

use meridian_rt::sys::{self, InputEvent, key};

use crate::apps::{Action, App, AppKind, Ctx, MenuItem, ctrl, error_text, file_name, unique_name};

const TOOLBAR_H: i32 = 64;
const STATUS_H: i32 = 26;
const IMAGE_X: i32 = 16;
const IMAGE_Y: i32 = TOOLBAR_H + 14;
const MAX_UNDO: usize = 8;

#[derive(Clone, Copy, PartialEq, Eq)]
enum Tool {
    Pencil,
    Brush,
    Eraser,
    Line,
    Rect,
    Ellipse,
    Fill,
    Picker,
}

const TOOLS: [(Tool, &str, char); 8] = [
    (Tool::Pencil, "Pencil", 'p'),
    (Tool::Brush, "Brush", 'b'),
    (Tool::Eraser, "Eraser", 'e'),
    (Tool::Fill, "Fill", 'f'),
    (Tool::Picker, "Colour picker", 'i'),
    (Tool::Line, "Line", 'l'),
    (Tool::Rect, "Rectangle", 'r'),
    (Tool::Ellipse, "Ellipse", 'o'),
];

const SIZES: [f32; 4] = [2.0, 5.0, 10.0, 18.0];

const PALETTE: [Color; 20] = [
    rgb(0x00, 0x00, 0x00),
    rgb(0x7F, 0x7F, 0x7F),
    rgb(0x88, 0x00, 0x15),
    rgb(0xED, 0x1C, 0x24),
    rgb(0xFF, 0x7F, 0x27),
    rgb(0xFF, 0xF2, 0x00),
    rgb(0x22, 0xB1, 0x4C),
    rgb(0x00, 0xA2, 0xE8),
    rgb(0x3F, 0x48, 0xCC),
    rgb(0xA3, 0x49, 0xA4),
    rgb(0xFF, 0xFF, 0xFF),
    rgb(0xC3, 0xC3, 0xC3),
    rgb(0xB9, 0x7A, 0x57),
    rgb(0xFF, 0xAE, 0xC9),
    rgb(0xFF, 0xC9, 0x0E),
    rgb(0xEF, 0xE4, 0xB0),
    rgb(0xB5, 0xE6, 0x1D),
    rgb(0x99, 0xD9, 0xEA),
    rgb(0x70, 0x92, 0xBE),
    rgb(0xC8, 0xBF, 0xE7),
];

pub struct Paint {
    image: Canvas,
    path: Option<String>,
    tool: Tool,
    color: Color,
    size: usize,
    undo: Vec<Canvas>,
    redo: Vec<Canvas>,
    /// Snapshot taken when the current stroke started (shapes redraw on it).
    base: Option<Canvas>,
    start: (i32, i32),
    last: (i32, i32),
    drawing: bool,
    modified: bool,
    pointer: Option<(i32, i32)>,
    prompt: Option<Prompt>,
    note: String,
    w: i32,
    h: i32,
}

/// Eight points around a circle per step of 2*pi/72, generated by rotation
/// (no trigonometry library is available).
fn ellipse_points(cx: f32, cy: f32, rx: f32, ry: f32) -> Vec<(f32, f32)> {
    let (c, s) = (0.996_194_7_f32, 0.087_155_74_f32); // cos/sin of 5 degrees
    let (mut x, mut y) = (1.0_f32, 0.0_f32);
    let mut pts = Vec::with_capacity(73);
    for _ in 0..=72 {
        pts.push((cx + x * rx, cy + y * ry));
        (x, y) = (x * c - y * s, x * s + y * c);
    }
    pts
}

impl Paint {
    pub fn new(path: Option<String>) -> Self {
        let mut p = Self {
            image: Canvas::new(820, 470, rgb(255, 255, 255)),
            path: None,
            tool: Tool::Brush,
            color: PALETTE[0],
            size: 1,
            undo: Vec::new(),
            redo: Vec::new(),
            base: None,
            start: (0, 0),
            last: (0, 0),
            drawing: false,
            modified: false,
            pointer: None,
            prompt: None,
            note: String::new(),
            w: 1000,
            h: 640,
        };
        if let Some(path) = path {
            p.open(&path);
        }
        p
    }

    fn open(&mut self, path: &str) {
        match sys::read_file(path).map_err(error_text).and_then(|d| bmp::decode(&d)) {
            Ok(img) => {
                self.image = img;
                self.path = Some(path.to_string());
                self.undo.clear();
                self.redo.clear();
                self.modified = false;
                self.note = format!("Opened {}", file_name(path));
            }
            Err(e) => self.note = format!("Cannot open {}: {e}", file_name(path)),
        }
    }

    fn save_to(&mut self, path: &str) -> Vec<Action> {
        let data = bmp::encode(&self.image);
        match sys::write_file(path, &data) {
            Ok(()) => {
                self.path = Some(path.to_string());
                self.modified = false;
                self.prompt = None;
                self.note = format!("Saved {} ({} KB)", path, data.len() / 1024);
                vec![Action::Notify(format!("Saved {}", file_name(path))), Action::FilesChanged]
            }
            Err(e) => {
                let msg = format!("Could not save: {}", error_text(e));
                match &mut self.prompt {
                    Some(p) => p.error = msg,
                    None => self.note = msg,
                }
                Vec::new()
            }
        }
    }

    fn ask_save_as(&mut self) {
        let name = unique_name("D:\\Pictures", "Drawing", "bmp");
        let suggested = match &self.path {
            Some(p) if !p.to_ascii_uppercase().starts_with("C:") => p.clone(),
            _ => format!("D:\\Pictures\\{name}"),
        };
        let mut prompt = Prompt::new("Save picture as", &suggested, "Save", 1);
        let start = suggested.rfind('\\').map_or(0, |i| suggested[..i + 1].chars().count());
        let end = suggested.rfind('.').map_or(suggested.chars().count(), |d| suggested[..d].chars().count());
        prompt.field.select(start, end);
        self.prompt = Some(prompt);
    }

    fn snapshot(&mut self) {
        self.undo.push(self.image.clone());
        if self.undo.len() > MAX_UNDO {
            self.undo.remove(0);
        }
        self.redo.clear();
        self.modified = true;
    }

    fn undo(&mut self) {
        if let Some(prev) = self.undo.pop() {
            self.redo.push(core::mem::replace(&mut self.image, prev));
        }
    }

    fn redo(&mut self) {
        if let Some(next) = self.redo.pop() {
            self.undo.push(core::mem::replace(&mut self.image, next));
        }
    }

    fn to_image(&self, x: i32, y: i32) -> (i32, i32) {
        (x - IMAGE_X, y - IMAGE_Y)
    }

    fn width(&self) -> f32 {
        match self.tool {
            Tool::Pencil => 1.0,
            Tool::Eraser => SIZES[self.size] * 2.0,
            _ => SIZES[self.size],
        }
    }

    fn stroke_color(&self) -> Color {
        if self.tool == Tool::Eraser { rgb(255, 255, 255) } else { self.color }
    }

    fn segment(&mut self, a: (i32, i32), b: (i32, i32)) {
        let (w, c) = (self.width(), self.stroke_color());
        let img = &mut self.image;
        if self.tool == Tool::Pencil {
            img.line(a.0 as f32 + 0.5, a.1 as f32 + 0.5, b.0 as f32 + 0.5, b.1 as f32 + 0.5, 1.2, c);
        } else {
            img.line(a.0 as f32 + 0.5, a.1 as f32 + 0.5, b.0 as f32 + 0.5, b.1 as f32 + 0.5, w, c);
            img.circle(b.0 as f32 + 0.5, b.1 as f32 + 0.5, w / 2.0, c);
        }
    }

    /// Redraws the shape being dragged from `start` to `end` on the base.
    fn shape(&mut self, end: (i32, i32)) {
        let Some(base) = &self.base else { return };
        self.image = base.clone();
        let (w, c) = (self.width(), self.color);
        let (x0, y0) = (self.start.0 as f32 + 0.5, self.start.1 as f32 + 0.5);
        let (x1, y1) = (end.0 as f32 + 0.5, end.1 as f32 + 0.5);
        let img = &mut self.image;
        match self.tool {
            Tool::Line => img.line(x0, y0, x1, y1, w, c),
            Tool::Rect => {
                for (a, b) in [((x0, y0), (x1, y0)), ((x1, y0), (x1, y1)), ((x1, y1), (x0, y1)), ((x0, y1), (x0, y0))] {
                    img.line(a.0, a.1, b.0, b.1, w, c);
                }
            }
            Tool::Ellipse => {
                let pts = ellipse_points(
                    (x0 + x1) / 2.0,
                    (y0 + y1) / 2.0,
                    math::abs(x1 - x0) / 2.0,
                    math::abs(y1 - y0) / 2.0,
                );
                for s in pts.windows(2) {
                    img.line(s[0].0, s[0].1, s[1].0, s[1].1, w, c);
                }
            }
            _ => {}
        }
    }

    fn flood_fill(&mut self, x: i32, y: i32) {
        let img = &mut self.image;
        let (w, h) = (img.w, img.h);
        if x < 0 || y < 0 || x >= w || y >= h {
            return;
        }
        let target = img.px[(y * w + x) as usize] | 0xFF00_0000;
        let fill = self.color | 0xFF00_0000;
        if target == fill {
            return;
        }
        let mut stack = vec![(x, y)];
        while let Some((sx, sy)) = stack.pop() {
            let row = (sy * w) as usize;
            let mut l = sx;
            while l > 0 && img.px[row + l as usize - 1] | 0xFF00_0000 == target {
                l -= 1;
            }
            let mut r = sx;
            while r + 1 < w && img.px[row + r as usize + 1] | 0xFF00_0000 == target {
                r += 1;
            }
            for i in l..=r {
                img.px[row + i as usize] = fill;
            }
            for ny in [sy - 1, sy + 1] {
                if ny < 0 || ny >= h {
                    continue;
                }
                let nrow = (ny * w) as usize;
                let mut i = l;
                while i <= r {
                    if img.px[nrow + i as usize] | 0xFF00_0000 == target {
                        stack.push((i, ny));
                        while i <= r && img.px[nrow + i as usize] | 0xFF00_0000 == target {
                            i += 1;
                        }
                    }
                    i += 1;
                }
            }
        }
    }

    fn prompt_submit(&mut self, purpose: u32, value: String) -> Vec<Action> {
        let path = value.trim().to_string();
        if purpose == 1 {
            let path = if path.contains('.') { path } else { format!("{path}.bmp") };
            return self.save_to(&path);
        }
        self.open(&path);
        if self.path.as_deref() == Some(path.as_str()) {
            self.prompt = None;
        } else if let Some(p) = &mut self.prompt {
            p.error = core::mem::take(&mut self.note);
        }
        Vec::new()
    }

    fn tool_rect(i: usize) -> Rect {
        Rect::new(10 + (i as i32 % 4) * 30, 6 + (i as i32 / 4) * 28, 26, 26)
    }
    fn size_rect(i: usize) -> Rect {
        Rect::new(144 + i as i32 * 30, 18, 26, 30)
    }
    fn swatch_rect(i: usize) -> Rect {
        Rect::new(330 + (i as i32 % 10) * 24, 8 + (i as i32 / 10) * 24, 20, 20)
    }
    fn button_rect(i: usize) -> Rect {
        Rect::new(600 + i as i32 * 74, 16, 68, 32)
    }
}

const BUTTONS: [&str; 5] = ["Undo", "Redo", "New", "Open", "Save"];

impl App for Paint {
    fn kind(&self) -> AppKind {
        AppKind::Paint
    }
    fn title(&self) -> String {
        let name = self.path.as_deref().map_or("Untitled", file_name);
        format!("{}{name} - Paint", if self.modified { "*" } else { "" })
    }
    fn size(&self) -> (i32, i32) {
        (1000, 640)
    }
    fn min_size(&self) -> (i32, i32) {
        (980, 360)
    }

    fn draw(&mut self, cv: &mut Canvas, r: Rect, cx: &mut Ctx) {
        let t = cx.theme;
        let f = &mut *cx.fonts;
        self.w = r.w;
        self.h = r.h;
        // Workspace behind the picture.
        cv.fill(r, if t.dark { rgb(0x1B, 0x1B, 0x1B) } else { rgb(0xDD, 0xE3, 0xEA) });
        let bar = Rect::new(r.x, r.y, r.w, TOOLBAR_H);
        cv.fill(bar, t.window());
        cv.fill(Rect::new(bar.x, bar.bottom() - 1, bar.w, 1), t.border());
        // Tools.
        for (i, (tool, _, _)) in TOOLS.iter().enumerate() {
            let b = Self::tool_rect(i).offset(r.x, r.y);
            if self.tool == *tool {
                cv.fill_rounded(b, 4, t.selection());
            }
            let c = t.text();
            let (x, y) = (b.x as f32, b.y as f32);
            match tool {
                Tool::Pencil => {
                    cv.line(x + 7.0, y + 19.0, x + 18.0, y + 8.0, 3.0, rgb(0xF5, 0x9E, 0x0B));
                    cv.line(x + 6.0, y + 20.0, x + 8.0, y + 18.0, 2.0, c);
                }
                Tool::Brush => {
                    cv.line(x + 15.0, y + 11.0, x + 20.0, y + 6.0, 2.5, rgb(0xB4, 0x53, 0x09));
                    cv.circle(x + 11.0, y + 16.0, 4.5, c);
                }
                Tool::Eraser => {
                    cv.line(x + 7.0, y + 18.0, x + 16.0, y + 9.0, 7.0, rgb(0xF4, 0x72, 0xB6));
                    cv.line(x + 7.0, y + 18.0, x + 10.0, y + 15.0, 7.0, rgb(0xE5, 0xE7, 0xEB));
                }
                Tool::Fill => {
                    cv.line(x + 8.0, y + 10.0, x + 16.0, y + 18.0, 6.0, c);
                    cv.circle(x + 19.0, y + 19.0, 2.5, rgb(0x25, 0x63, 0xEB));
                }
                Tool::Picker => {
                    cv.line(x + 7.0, y + 19.0, x + 15.0, y + 11.0, 2.0, c);
                    cv.circle(x + 17.0, y + 9.0, 3.5, c);
                }
                Tool::Line => cv.line(x + 6.0, y + 20.0, x + 20.0, y + 6.0, 1.6, c),
                Tool::Rect => cv.stroke(Rect::new(b.x + 6, b.y + 8, 14, 11), c),
                Tool::Ellipse => cv.ring(x + 13.0, y + 13.0, 7.0, 1.4, c),
            }
        }
        // Sizes.
        f.draw(cv, r.x + 144, r.y + 2, "Size", 12, Weight::Regular, t.text_dim());
        for (i, s) in SIZES.iter().enumerate() {
            let b = Self::size_rect(i).offset(r.x, r.y);
            if self.size == i {
                cv.fill_rounded(b, 4, t.selection());
            }
            cv.circle(b.x as f32 + 13.0, b.y as f32 + 15.0, (s / 2.0).min(11.0), t.text());
        }
        // Current colour and palette.
        let cur = Rect::new(r.x + 280, r.y + 12, 40, 40);
        cv.rounded_box(cur, 6, t.border(), self.color);
        for (i, c) in PALETTE.iter().enumerate() {
            let b = Self::swatch_rect(i).offset(r.x, r.y);
            if *c == self.color {
                cv.fill_rounded(b.grow(2), 4, t.accent);
            }
            cv.rounded_box(b, 3, shade(*c, -40), *c);
        }
        for (i, label) in BUTTONS.iter().enumerate() {
            let b = Self::button_rect(i).offset(r.x, r.y);
            let enabled = match i {
                0 => !self.undo.is_empty(),
                1 => !self.redo.is_empty(),
                _ => true,
            };
            let base = if t.dark { rgb(0x37, 0x37, 0x37) } else { rgb(0xFB, 0xFB, 0xFB) };
            let bg = if i == 4 { t.accent } else { base };
            cv.rounded_box(b, 5, if i == 4 { bg } else { t.border() }, bg);
            let fg = if i == 4 {
                t.accent_text()
            } else if enabled {
                t.text()
            } else {
                t.text_dim()
            };
            let tw = f.measure(label, 14, Weight::Regular);
            f.draw(cv, b.x + (b.w - tw) / 2, b.y + 7, label, 14, Weight::Regular, fg);
        }
        // The picture with a drop shadow.
        let img = Rect::new(r.x + IMAGE_X, r.y + IMAGE_Y, self.image.w, self.image.h);
        let area = Rect::new(r.x, r.y + TOOLBAR_H, r.w, r.h - TOOLBAR_H - STATUS_H);
        let old = cv.clip();
        cv.set_clip(area.intersect(&old).unwrap_or(area));
        cv.shadow(img, 2, 0, 8, 60);
        cv.blit(&self.image, self.image.bounds(), img.x, img.y);
        cv.set_clip(old);
        // Prompt and status bar.
        if let Some(p) = &mut self.prompt {
            p.draw(cv, f, &t, Rect::new(r.x, r.y, r.w, r.h - STATUS_H));
        }
        let sb = Rect::new(r.x, r.bottom() - STATUS_H, r.w, STATUS_H);
        cv.fill(sb, t.window());
        cv.fill(Rect::new(sb.x, sb.y, sb.w, 1), t.border());
        let tool = TOOLS.iter().find(|x| x.0 == self.tool).map_or("", |x| x.1);
        let pos = self.pointer.map_or(String::new(), |(x, y)| format!("{x}, {y} px     "));
        let left = if self.note.is_empty() {
            format!("{pos}{} x {} px     {tool}", self.image.w, self.image.h)
        } else {
            format!("{pos}{}", self.note)
        };
        f.draw_fit(cv, sb.x + 12, sb.y + 5, &left, sb.w - 24, 12, Weight::Regular, t.text_dim());
    }

    fn click(&mut self, x: i32, y: i32, _double: bool, cx: &mut Ctx) -> Vec<Action> {
        if let Some(p) = &mut self.prompt {
            let content = Rect::new(0, 0, self.w, self.h - STATUS_H);
            if y >= content.bottom() - PROMPT_H {
                let purpose = p.purpose;
                return match p.click(cx.fonts, content, x, y) {
                    PromptEvent::Submit(v) => self.prompt_submit(purpose, v),
                    PromptEvent::Cancel => {
                        self.prompt = None;
                        Vec::new()
                    }
                    PromptEvent::None => Vec::new(),
                };
            }
        }
        if y < TOOLBAR_H {
            for (i, (tool, _, _)) in TOOLS.iter().enumerate() {
                if Self::tool_rect(i).contains(x, y) {
                    self.tool = *tool;
                }
            }
            for i in 0..SIZES.len() {
                if Self::size_rect(i).contains(x, y) {
                    self.size = i;
                }
            }
            for (i, c) in PALETTE.iter().enumerate() {
                if Self::swatch_rect(i).contains(x, y) {
                    self.color = *c;
                }
            }
            for i in 0..BUTTONS.len() {
                if Self::button_rect(i).contains(x, y) {
                    return self.menu(i as u32 + 1, cx);
                }
            }
            return Vec::new();
        }
        let (ix, iy) = self.to_image(x, y);
        if ix < 0 || iy < 0 || ix >= self.image.w || iy >= self.image.h {
            return Vec::new();
        }
        self.note.clear();
        match self.tool {
            Tool::Fill => {
                self.snapshot();
                self.flood_fill(ix, iy);
            }
            Tool::Picker => {
                self.color = self.image.px[(iy * self.image.w + ix) as usize] | 0xFF00_0000;
                self.tool = Tool::Brush;
            }
            Tool::Line | Tool::Rect | Tool::Ellipse => {
                self.snapshot();
                self.base = Some(self.image.clone());
                self.start = (ix, iy);
                self.drawing = true;
            }
            _ => {
                self.snapshot();
                self.drawing = true;
                self.last = (ix, iy);
                self.segment((ix, iy), (ix, iy));
            }
        }
        Vec::new()
    }

    fn drag(&mut self, x: i32, y: i32, _cx: &mut Ctx) -> bool {
        let p = self.to_image(x, y);
        self.pointer = Some(p);
        if !self.drawing {
            return true;
        }
        match self.tool {
            Tool::Line | Tool::Rect | Tool::Ellipse => self.shape(p),
            _ => {
                let last = self.last;
                self.segment(last, p);
                self.last = p;
            }
        }
        true
    }

    fn release(&mut self, _x: i32, _y: i32, _cx: &mut Ctx) -> Vec<Action> {
        self.drawing = false;
        self.base = None;
        Vec::new()
    }

    fn hover(&mut self, x: i32, y: i32) -> bool {
        let (ix, iy) = self.to_image(x, y);
        let inside = ix >= 0 && iy >= 0 && ix < self.image.w && iy < self.image.h;
        let new = if inside { Some((ix, iy)) } else { None };
        let changed = new != self.pointer;
        self.pointer = new;
        changed
    }

    fn right_click(&mut self, x: i32, y: i32, _cx: &mut Ctx) -> Vec<Action> {
        vec![Action::Menu(
            vec![
                MenuItem::when("Undo", 1, !self.undo.is_empty()),
                MenuItem::when("Redo", 2, !self.redo.is_empty()),
                MenuItem::separator(),
                MenuItem::new("Clear picture", 6),
                MenuItem::new("Save", 5),
            ],
            x,
            y,
        )]
    }

    fn menu(&mut self, id: u32, _cx: &mut Ctx) -> Vec<Action> {
        match id {
            1 => self.undo(),
            2 => self.redo(),
            3 | 6 => {
                self.snapshot();
                let (w, h) = (self.image.w, self.image.h);
                self.image = Canvas::new(w, h, rgb(255, 255, 255));
                if id == 3 {
                    self.path = None;
                    self.undo.clear();
                    self.modified = false;
                }
            }
            4 => {
                self.prompt = Some(Prompt::new("Open picture", "D:\\Pictures\\", "Open", 2));
            }
            5 => match self.path.clone() {
                Some(p) if !p.to_ascii_uppercase().starts_with("C:") => return self.save_to(&p),
                _ => self.ask_save_as(),
            },
            _ => {}
        }
        Vec::new()
    }

    fn key(&mut self, e: &InputEvent, cx: &mut Ctx) -> Vec<Action> {
        if let Some(p) = &mut self.prompt {
            let purpose = p.purpose;
            return match p.key(e, cx.clipboard) {
                PromptEvent::Submit(v) => self.prompt_submit(purpose, v),
                PromptEvent::Cancel => {
                    self.prompt = None;
                    Vec::new()
                }
                PromptEvent::None => Vec::new(),
            };
        }
        if ctrl(e, 'z') {
            return self.menu(1, cx);
        }
        if ctrl(e, 'y') {
            return self.menu(2, cx);
        }
        if ctrl(e, 's') {
            return self.menu(5, cx);
        }
        if ctrl(e, 'o') {
            return self.menu(4, cx);
        }
        if e.key == key::CHAR {
            let c = char::from_u32(e.ch).unwrap_or(' ').to_ascii_lowercase();
            if let Some((tool, _, _)) = TOOLS.iter().find(|x| x.2 == c) {
                self.tool = *tool;
            }
            match c {
                '[' => self.size = self.size.saturating_sub(1),
                ']' => self.size = (self.size + 1).min(SIZES.len() - 1),
                _ => {}
            }
        }
        Vec::new()
    }
}
